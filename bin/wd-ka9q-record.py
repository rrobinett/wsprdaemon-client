#!/usr/bin/env python3
"""wd-ka9q-record — KA9Q WSPR recording daemon for wsprdaemon v4.

Generates a wspr-recorder config from env vars and execs
/opt/wsprdaemon-client/venv/bin/wspr-recorder (github.com/mijahauan/wspr-recorder
by AC0G).  wspr-recorder handles channel lifecycle via RadiodControl,
RTP multicast reception, minute-aligned WAV writing, gap detection,
quality JSON sidecars, and health monitoring.

WWV/CHU IQ recording is handled by the hf-timestd peer service
(github.com/mijahauan/hf-timestd).  No ka9q_wwv receivers appear in
wsprdaemon.conf.

Environment variables (set by systemd EnvironmentFile):
    WD_RADIOD_STATUS    Radiod status/control DNS  (e.g. k3lr-rx888-status.local)
    WD_RECEIVER_NAME    Receiver name              (e.g. KA9Q_0)
    WD_BANDS            Space-separated band list  (e.g. "630 80 40 20")
    WD_RECORDING_DIR    Spool root for this receiver
    WD_GAIN_DB          Audio channel gain in dB   (default: 0 — no gain, matches v3)

Per-band decode modes are read from the corresponding wd-decode env files at
/etc/wsprdaemon/env/wd-decode@{RX_NAME}-{band}.env (WD_RECEIVER_MODES field).
This drives the wspr-recorder ring-buffer size and WAV period lengths.

WAV output: YYYYMMDDTHHMMSSz_{freq_hz}_usb.wav  (matches kiwi format)
"""

import os
import shutil
import sys
import logging
from pathlib import Path
from typing import List

# wdlib is in /opt/wsprdaemon-client/lib (installed) or relative to this script
_HERE = Path(__file__).resolve().parent
for _p in ['/opt/wsprdaemon-client/lib', str(_HERE.parent / 'lib')]:
    if Path(_p).exists() and _p not in sys.path:
        sys.path.insert(0, _p)

from wdlib.envgen import BAND_FREQ_HZ  # noqa: E402

log = logging.getLogger('wd-ka9q-record')

RADIOD_STATUS = os.environ['WD_RADIOD_STATUS']
RX_NAME       = os.environ['WD_RECEIVER_NAME']
BANDS         = os.environ['WD_BANDS'].split()
RECORDING_DIR = Path(os.environ['WD_RECORDING_DIR'])
GAIN_DB       = float(os.environ.get('WD_GAIN_DB', '0'))
ENV_DIR       = Path(os.environ.get('WD_ENV_DIR', '/etc/wsprdaemon/env'))

def _resolve_wspr_recorder() -> str:
    """Find the wspr-recorder binary.

    Look on $PATH first (covers /usr/local/bin/wspr-recorder, the location
    that `smd install wspr-recorder` writes to via its install.sh) and
    fall back to the legacy venv path that earlier versions of this
    script hard-coded.  When neither exists we still return the legacy
    path so the operator gets the well-known error message; a missing
    wspr-recorder is a setup gap, not something to silently paper over.
    """
    found = shutil.which('wspr-recorder')
    if found:
        return found
    legacy = '/opt/wsprdaemon-client/venv/bin/wspr-recorder'
    return legacy


WSPR_RECORDER = _resolve_wspr_recorder()


def _read_band_modes(band: str) -> List[str]:
    """Read WD_RECEIVER_MODES from the wd-decode env file for this band.

    Returns a list of mode strings (e.g. ['W2', 'F2', 'F5']).
    Falls back to ['W2'] if the env file is absent or has no modes line.
    """
    env_file = ENV_DIR / f'wd-decode@{RX_NAME}-{band}.env'
    try:
        for line in env_file.read_text().splitlines():
            line = line.strip()
            if line.startswith('WD_RECEIVER_MODES='):
                raw = line.split('=', 1)[1].strip()
                modes = [m.strip() for m in raw.split(':') if m.strip()]
                if modes:
                    return modes
    except OSError:
        pass
    return ['W2']


def _build_toml(band_freq_pairs: List[tuple]) -> str:
    """Generate a wspr-recorder config.toml with per-band [[band]] sections."""
    ipc_sock  = f'/run/wsprdaemon/wspr-rec-{RX_NAME}.sock'
    stat_file = str(RECORDING_DIR / 'wspr-recorder-status.json')

    band_sections = []
    for band, freq_hz in band_freq_pairs:
        modes = _read_band_modes(band)
        modes_toml = ', '.join(f'"{m}"' for m in modes)
        band_sections.append(
            f'[[band]]\n'
            f'frequency = "{freq_hz}"  # {band}m\n'
            f'modes = [{modes_toml}]\n'
        )

    return f"""\
# Auto-generated by wd-ka9q-record for {RX_NAME}
# Do not edit — regenerated on each service start.

[radiod]
status_address = "{RADIOD_STATUS}"

[recorder]
output_dir     = "{RECORDING_DIR}"
sample_format  = "float32"
max_file_age_minutes = 60
max_files_per_band   = 60
ipc_socket  = "{ipc_sock}"
status_file = "{stat_file}"

[timing]
# RX888 is GPSDO-disciplined — RTP timestamps are accurate to parts per
# billion, so RtpSyncStrategy is always the right choice for minute-
# boundary arithmetic.  authority="auto" still uses RtpSyncStrategy;
# what it adds is that the one-time RTP->UTC correlation is taken from
# /run/hf-timestd/authority.json (precise, sub-us) when hf-timestd is
# running, instead of from datetime.now() (delivery-latency-bound,
# ~hundreds of ms error).  Falls back automatically to wall-clock
# correlation in standalone mode.
authority = "auto"

[channel_defaults]
sample_rate = 12000
mode        = "usb"
encoding    = "f32"
agc         = false
gain        = {GAIN_DB}
low         = 1300
high        = 1700

{''.join(band_sections)}"""


def main() -> int:
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)sZ %(name)s %(levelname)s %(message)s',
        datefmt='%Y-%m-%dT%H:%M:%S',
    )

    band_freq_pairs = [(b, BAND_FREQ_HZ[b]) for b in BANDS if b in BAND_FREQ_HZ]
    unknown         = [b for b in BANDS if b not in BAND_FREQ_HZ]
    if unknown:
        log.warning('unknown bands (skipped): %s', unknown)
    if not band_freq_pairs:
        log.error('no valid bands configured')
        return 1

    RECORDING_DIR.mkdir(parents=True, exist_ok=True)

    cfg_path = RECORDING_DIR / 'wspr-recorder.toml'
    cfg_path.write_text(_build_toml(band_freq_pairs))
    for band, freq_hz in band_freq_pairs:
        modes = _read_band_modes(band)
        log.info('  %sm (%d Hz): %s', band, freq_hz, ':'.join(modes))
    log.info('exec wspr-recorder -c %s  (bands: %s)', cfg_path, BANDS)

    os.execv(WSPR_RECORDER, [WSPR_RECORDER, '-c', str(cfg_path)])
    log.error('execv failed — wspr-recorder not found at %s', WSPR_RECORDER)
    return 1


if __name__ == '__main__':
    sys.exit(main())
